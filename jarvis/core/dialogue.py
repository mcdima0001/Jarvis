"""Недавний разговор: что сказал владелец и что ответил ассистент.

До сих пор у ассистента не было памяти **на реплики**. Состояние между
командами существовало (`state.py` — режимы, `situation.py` — обстановка,
`pending.py` — заданный вопрос), но сам разговор нигде не хранился: каждая
фраза разбиралась и отвечалась с чистого листа.

Вот как это выглядело в живом запуске 12.09.2026, три реплики подряд:

    владелец:  Джарвис, напиши...
    ассистент: Не понял, кому написать.
    владелец:  Роме.
    ассистент: А что написать Ромка Малютка?
    владелец:  <ответ на вопрос>
    ассистент: Не могу найти информацию по запросу..., сэр.

Последняя реплика — ответ на вопрос, который ассистент задал сам десять секунд
назад. Он его не узнал, потому что не помнил, что спрашивал: фраза ушла в
роутер как новая команда и разобралась в свободный разговор.

**Что это, а что нет.** Это короткая память сеанса, а не память проекта: она
живёт в оперативной памяти, не переживает перезапуск и стареет сама.
Долговременное («владелец живёт в Твери») — дело `memory/`, и путать их нельзя.
Здесь другая задача: чтобы «а теперь погромче», «нет, второму» и ответ на
заданный вопрос понимались как продолжение, а не как новая команда ниоткуда.

Два ограничения, и оба по делу:

* **Срок годности.** Разговор часовой давности — не контекст, а помеха: модель
  примет его за продолжение и ответит невпопад. После `TTL_S` молчания реплики
  забываются, и следующая фраза начинает разговор с чистого листа.
* **Предел числа реплик.** Разговор уходит в модель на каждом вопросе, то есть
  оплачивается. `TURNS` реплик — это десятки токенов, а не сотни.

**Наружу это уходит.** Реплики попадают в облако вместе с вопросом, и теперь не
только последняя. Для ассистента, который и так расшифровывает речь в облаке,
это не новое качество, но знать стоит: выключается `router.dialogue`.
"""

from __future__ import annotations

import time
from dataclasses import dataclass

from .llm import Message

#: Сколько последних реплик держать (считая обе стороны). Три обмена — это ровно
#: то, на что ссылаются словами «а теперь», «нет, другому», «ага, давай».
TURNS = 6

#: Через сколько секунд молчания разговор считается законченным. Пять минут:
#: столько человек ещё помнит, о чём была речь, а через час «повтори» значит
#: уже совсем другое.
TTL_S = 300.0

#: Предел длины одной реплики. Пересказ переписки или ответ поиска целиком в
#: истории не нужен: важно, **о чём** шла речь, а не весь текст дословно.
MAX_TEXT = 200

_TAIL = {
    "ru": "Ты только что сказал: «{text}»",
    "en": 'You just said: "{text}"',
}


@dataclass(frozen=True, slots=True)
class Turn:
    """Одна реплика разговора: кто сказал и что."""

    #: `user` или `assistant` — те же роли, что у модели, чтобы не переводить.
    role: str
    text: str
    #: Монотонные секунды, когда это прозвучало.
    at: float

    def stale(self, now: float, ttl: float) -> bool:
        """Устарела ли реплика."""
        return now - self.at >= ttl


class Conversation:
    """Последние реплики разговора — общая память на весь ассистент.

    Один экземпляр на систему, как режимы и обстановка: голос, клавиатура и
    будущий вход из Telegram — это разные входы **одного** разговора, а не три
    независимых. Заводить свою историю каждому означало бы, что ассистент
    помнит сказанное голосом и не помнит напечатанное минуту назад.
    """

    def __init__(
        self, *, turns: int = TURNS, ttl_s: float = TTL_S, enabled: bool = True
    ) -> None:
        self._limit = max(1, turns)
        self._ttl = max(0.0, ttl_s)
        self._enabled = enabled
        self._turns: list[Turn] = []

    @property
    def enabled(self) -> bool:
        """Помнит ли ассистент разговор вообще.

        Выключенный не запоминает ничего, а не «запоминает и не показывает»:
        реплики не должны копиться в памяти процесса, если владелец их помнить
        не просил.
        """
        return self._enabled

    def said(self, text: str, *, now: float | None = None) -> None:
        """Запомнить реплику владельца."""
        self._add("user", text, now)

    def replied(self, text: str, *, now: float | None = None) -> None:
        """Запомнить ответ ассистента."""
        self._add("assistant", text, now)

    def _add(self, role: str, text: str, now: float | None) -> None:
        line = " ".join(str(text).split())[:MAX_TEXT]
        if not self._enabled or not line:
            return
        moment = time.monotonic() if now is None else now
        # Протухшее выносим при записи, а не по таймеру: разговор — вещь
        # ленивая, и заводить ради него фоновую задачу незачем.
        self._turns = [turn for turn in self._turns if not turn.stale(moment, self._ttl)]
        self._turns.append(Turn(role=role, text=line, at=moment))
        del self._turns[: max(0, len(self._turns) - self._limit)]

    def clear(self) -> None:
        """Забыть разговор — «забудь, о чём говорили»."""
        self._turns.clear()

    def turns(self, *, now: float | None = None) -> tuple[Turn, ...]:
        """Живые реплики, от старых к новым. Протухшие отсеиваются по дороге."""
        moment = time.monotonic() if now is None else now
        self._turns = [turn for turn in self._turns if not turn.stale(moment, self._ttl)]
        return tuple(self._turns)

    def messages(self, *, now: float | None = None) -> list[Message]:
        """Разговор в виде реплик для модели.

        Готовая история, а не пересказ: модель понимает роли сама, и
        расписывать «владелец сказал, ты ответил» значит платить лишними
        токенами за то, что формат выражает бесплатно.
        """
        return [
            Message.assistant(turn.text)
            if turn.role == "assistant"
            else Message.user(turn.text)
            for turn in self.turns(now=now)
        ]

    def last_reply(self, *, now: float | None = None) -> str:
        """Последнее сказанное ассистентом, если это было только что."""
        for turn in reversed(self.turns(now=now)):
            if turn.role == "assistant":
                return turn.text
        return ""

    def describe(self, language: str = "ru", *, now: float | None = None) -> str:
        """Одна строка для подсказки разбора: что ассистент сказал последним.

        Именно одна, и это выбор, а не лень. Подсказка разбора уходит в модель
        на **каждой** неузнанной фразе вместе с каталогом инструментов — самая
        дорогая строка в системе. Весь разговор туда не нужен: случай, который
        ломался, — ответ на заданный вопрос, и для него хватает знания, что
        вопрос был и какой. Полная история идёт в свободный разговор, где она и
        нужна и где платится один раз.
        """
        reply = self.last_reply(now=now)
        if not reply:
            return ""
        code = language if language in _TAIL else "ru"
        return _TAIL[code].format(text=reply)
