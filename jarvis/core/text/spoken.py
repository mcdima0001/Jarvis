"""Сравнение услышанного с написанным.

Одна и та же задача возникает всюду, где голос встречается с текстом, который
писали не мы: название программы в меню «Пуск», заголовок вкладки, имя сайта.
Человек произносит «маршал тех», распознавание пишет «MarshallTech», а на
странице стоит «МаршалТех» — три записи одного слова, и ни одна не совпадает с
другой побуквенно.

Три приёма, от точного к грубому:

* :func:`squash` — выбросить всё, кроме букв и цифр. Разделители внутри
  названия расставлены как попало: «Яндекс.Музыка», «яндекс музыка»,
  «obs-studio».
* :func:`romanize` — записать кириллицу латиницей. Нечёткое сравнение между
  алфавитами бесполезно: похожесть «джарвис» и «jarvis» равна нулю.
* :func:`skeleton` — оставить согласные, выровняв английское написание с
  русским произношением. Гласные на слух плывут сильнее всего («зум» против
  «zoom»), согласные остаются.

Костяк сравнивается только на точное совпадение: приём и так грубый, а
нечёткость поверх него даёт ложные попадания.
"""

from __future__ import annotations

import re

#: Кириллица в латиницу — «обс» должно находить «OBS».
CYRILLIC_TO_LATIN: dict[str, str] = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
    "ж": "zh", "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "h", "ц": "c", "ч": "ch", "ш": "sh", "щ": "sch",
    "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
}

#: Английское написание против русского произношения: photoshop — «фотошоп»,
#: notion — «ноушен», firefox — «файрфокс». Правила выравнивают обе записи.
PHONETIC: tuple[tuple[str, str], ...] = (
    ("tion", "shn"), ("ph", "f"), ("ck", "k"), ("x", "ks"),
    ("w", "v"), ("j", "dz"), ("qu", "kv"), ("c", "k"),
    # После c→k: «Chrome» становится «khrome», а по-русски это «хром».
    ("kh", "h"),
)

_VOWELS = "aeiouy"

#: Всё, что не буква и не цифра. Алфавиты перечислены явно: чужие символы в
#: названиях программ и сайтов означают мусор, а не слово.
_NOT_LETTER = re.compile(r"[^a-zа-яё0-9]+")


def squash(text: str) -> str:
    """Оставить только буквы и цифры в нижнем регистре.

    Пробелы и знаки внутри названия ничего не значат: «OBS Studio»,
    «obs-studio», «Яндекс.Музыка» — это одно и то же слово.
    """
    return _NOT_LETTER.sub("", text.strip().lower())


def romanize(text: str) -> str:
    """Записать кириллицу латиницей для сравнения названий."""
    return "".join(CYRILLIC_TO_LATIN.get(char, char) for char in text)


def skeleton(text: str) -> str:
    """Согласный костяк слова — то, что переживает произношение вслух."""
    lowered = romanize(text.strip().lower())
    for source, target in PHONETIC:
        lowered = lowered.replace(source, target)
    letters = [char for char in lowered if char.isalnum() and char not in _VOWELS]
    # Двойные согласные на слух неразличимы: «Discord» и «дискорд».
    return "".join(
        char
        for index, char in enumerate(letters)
        if index == 0 or char != letters[index - 1]
    )
