"""Составная просьба узнаётся до шаблонов, иначе шаблон заберёт её целиком.

Живой запуск 12.09.2026: «найди инстаграм этой девушки на экране» ушло в
`search.web_search` с этой самой фразой в качестве запроса, и ассистент бодро
ответил «Нашёл 3. Первый: Акиньшина, Оксана Сергеевна». На экран он при этом
не посмотрел ни разу.

**Виноват не шаблон, а порядок.** Шаблоны стоят первыми потому, что они
бесплатны, и это главная экономия проекта: четыре сотни типовых фраз не доходят
до модели вовсе. Но шаблон `найди {query}` сопоставляется с началом фразы и
забирает **весь** хвост, каким бы он ни был. Просьба, для которой одного вызова
не хватает, до модели после этого не доживает — а решить, что её надо разбить на
шаги, может только модель.

Поэтому перед шаблонами встаёт дешёвая проверка: **не составная ли это
просьба**. Проверка местная, без сети и без модели, и намеренно узкая — она
отвечает не «что это за команда», а только «хватит ли тут одного вызова».
Ответила «нет» — просьба уходит в `core.plan`, и дальше всё как обычно: модель
видит каталог, выбирает шаги, необратимое переспрашивает.

**Главное правило тут — молчать в сомнении.** Лишнее срабатывание стоит дорого:
типовая команда вместо бесплатного шаблона уедет в модель и вернётся планом из
одного шага. Поэтому признак требует **двух** совпадений сразу, и оба списка
короткие.

Признак ровно один, и он взят из живых промахов: **просьба ссылается на то, что
ассистент ещё не видел** («на экране», «эта фотография»), **и просит сделать с
этим что-то, чего зрение не умеет** («найди», «открой», «отправь»). Одного
упоминания экрана мало: «что на экране» — обычный однократный вызов, и он обязан
остаться бесплатным.
"""

from __future__ import annotations

import logging

from jarvis.core.contracts import Intent, Utterance

logger = logging.getLogger(__name__)

#: На что ссылаются, когда просят посмотреть. Сюда же указательные обороты о
#: снимке: «найди место, где сделана эта фотография» экрана не упоминает вовсе.
SOURCES = (
    "на экране",
    "на экран",
    "с экрана",
    "на скрине",
    "на мониторе",
    "на фото",
    "на фотографии",
    "на картинке",
    "на снимке",
    "на изображении",
    "эта фотография",
    "эту фотографию",
    "этой фотографии",
    "это фото",
    "этого фото",
    "этот снимок",
    "этого снимка",
    "эту картинку",
    "этой картинки",
    "on the screen",
    "in the photo",
    "in this photo",
    "on this picture",
)

#: Действия, которых зрение не умеет. Список короткий намеренно: каждое лишнее
#: слово — это риск увести бесплатную команду в модель. Сюда попадает только то,
#: что заведомо требует **другого** инструмента после того, как посмотрели.
ACTIONS = (
    "найди",
    "найти",
    "поищи",
    "погугли",
    "открой",
    "открыть",
    "отправь",
    "перешли",
    "напиши",
    "скачай",
    "сохрани",
    "запиши",
    "закажи",
    "переведи",
    "find",
    "search",
    "open",
    "send",
    "download",
    "save",
)

#: Слова, после которых «найди» и «открой» относятся к самой странице, а не к
#: миру: «найди на экране кнопку оплатить» — это нажатие, а не поиск в сети, и
#: такой просьбой занимается скилл страницы. Плана тут не нужно.
ON_PAGE = ("кнопк", "ссылк", "поле", "button", "link")


def needs_a_plan(text: str) -> bool:
    """Хватит ли одного вызова на эту просьбу. ``False`` — хватит.

    Два совпадения обязательны: ссылка на то, что надо сперва увидеть, и
    действие, которого зрение не умеет. По одному признаку не срабатываем — «что
    на экране» и «найди рецепт борща» обязаны остаться бесплатными.
    """
    low = " ".join(text.split()).lower()
    if not any(source in low for source in SOURCES):
        return False
    if not any(_has_word(low, action) for action in ACTIONS):
        return False
    if any(hint in low for hint in ON_PAGE):
        return False
    return True


def _has_word(text: str, word: str) -> bool:
    """Есть ли слово в тексте именно словом, а не куском другого слова.

    Иначе «открой» находится внутри «открой-ка», что как раз хорошо, но «найди»
    нашлось бы внутри выдуманного «донайди». Сравниваем по границам вручную:
    тянуть регулярное выражение ради одного правила не стоит.
    """
    start = 0
    while True:
        found = text.find(word, start)
        if found < 0:
            return False
        before = text[found - 1] if found else " "
        after = text[found + len(word) :][:1] or " "
        if not before.isalpha() and not after.isalpha():
            return True
        start = found + 1


class PlanResolver:
    """Составную просьбу отдаёт `core.plan`, не доводя до шаблонов."""

    def __init__(self, tool: str = "core.plan", *, argument: str = "goal") -> None:
        self._tool = tool
        self._argument = argument

    @property
    def name(self) -> str:
        """Имя резолвера."""
        return "plan"

    async def resolve(self, utterance: Utterance) -> Intent | None:
        """Отдать просьбу целиком в план, если одного вызова ей мало."""
        text = utterance.cleaned.strip()
        if not text or not needs_a_plan(text):
            return None
        logger.info(
            "Просьба составная (нужно сперва посмотреть): %r -> %s", text, self._tool
        )
        return Intent(
            tool=self._tool,
            # Цель — фраза владельца целиком и своими словами: резать её нельзя,
            # в отрезанном как раз и лежит вторая половина дела.
            arguments={self._argument: text},
            confidence=1.0,
            resolver=self.name,
            utterance=utterance.text,
        )
