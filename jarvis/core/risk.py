"""Какие кнопки руки агента не нажимают сами.

Руки плана (25.09.2026) нажимают по имени элемента — в окнах Windows через
дерево доступности, на странице через расширение. Правило проекта «план не даёт
новых прав» требует, чтобы необратимое план сам не делал. Но пометить
необратимым весь инструмент «нажми» нельзя: тогда план спрашивал бы разрешения
на каждую цифру калькулятора и каждую вкладку ютуба.

Поэтому решает **название кнопки**: «Семь», «Подписки», «Далее» нажимаются
сами, а «Удалить», «Отправить», «Оплатить» — нет. Отказ говорит, во что
упёрлись, и владелец скажет ту же команду прямо: на прямую команду голосом
правило не распространяется.

Список один на всю систему: окна и страница не должны разойтись в том, что
считать необратимым.
"""

from __future__ import annotations

#: Начала слов, за которыми стоит необратимое. Начала, а не слова целиком:
#: «удалить», «удаление», «удалённо» ловятся одним «удал». Сравнение идёт **с
#: начала слова**: иначе «order» нашёлся бы в «border», а «post» — в «compost».
#: Лишний отказ стоит одной повторённой команды, лишнее нажатие — удалённого
#: файла.
RISKY_STEMS: tuple[str, ...] = (
    # потерять
    "удал", "стер", "очист", "сброс", "форматир", "delete", "remove", "erase", "reset", "wipe",
    # отправить от имени владельца
    "отправ", "опубликов", "поделит", "ответит всем", "send", "publish", "post", "share",
    # деньги
    "оплат", "купит", "покуп", "заказ", "перевест", "перевод средств", "pay", "buy",
    "purchase", "checkout", "order",
    # согласия и учётные записи
    # «Подписки» на ютубе — просто раздел, поэтому не «подпис», а подписать
    # документ отдельным словом; «sign» без продолжения ловил бы и «Sign in».
    "подтверд", "принят", "соглас", "подписать", "confirm", "accept", "agree",
    "выйти из", "выход из аккаунт", "log out", "sign out",
    # система
    "выключ", "перезагруз", "завершит работу", "shut down", "restart",
    "установит", "install", "uninstall",
)


def risky(label: str) -> bool:
    """Нажимать ли это только по прямой команде. Чистая функция — её проверяют тесты."""
    text = " " + " ".join(label.lower().replace("ё", "е").split())
    return any(f" {stem}" in text for stem in RISKY_STEMS)
