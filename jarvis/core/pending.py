"""Переспросить и понять ответ: единственное состояние между репликами.

Всё остальное в системе устроено как «вопрос — ответ» за один заход: реплика
пришла, команда выполнилась, разговор кончился. Из-за этого ассистент при
сомнении мог только угадать или сказать «не понял», а агентный цикл, дойдя до
необратимого шага, только отказаться. Обе дыры закрываются одним умением:
**задать вопрос и помнить, что следующая реплика — ответ на него**.

**Ответ человека и есть разрешение.** Правило проекта гласит, что план не даёт
новых прав; голос владельца их даёт. Поэтому подтверждённый шаг выполняется
напрямую, точно так же, как если бы ту же команду сказали вслух с самого начала.

**Разбор ответа намеренно строгий.** Всё, что не опознано как согласие или
отказ, ответом не считается: вопрос снимается, а реплика идёт обычным путём.
Ошибиться в эту сторону значит переспросить лишний раз; ошибиться в другую —
отправить сообщение не тому человеку.
"""

from __future__ import annotations

import re
import time
from dataclasses import dataclass

from jarvis.core.contracts import Intent

#: Сколько живёт заданный вопрос, секунд.
#:
#: Полторы минуты — это «успел подумать и ответить», но не «вспомнил через час и
#: сказал да чему-то забытому». Протухший вопрос не срабатывает молча: он просто
#: перестаёт существовать.
TTL = 90.0

#: Длиннее этого реплика ответом не считается: на «да или нет» так не отвечают,
#: а вот команда из пяти слов — запросто.
MAX_WORDS = 5

#: Слова, любое из которых делает реплику отказом.
#:
#: Проверяются **первыми** и по одному вхождению, потому что отказ бывает внутри
#: согласия по форме: «конечно нет» начинается с «конечно».
NO_MARKERS = frozenset({
    "нет", "не", "отмена", "отставить", "стоп", "забудь", "забей", "отмени",
    "нельзя", "погоди", "подожди",
    "no", "nope", "cancel", "stop", "dont", "never", "negative", "nevermind",
})

#: Слова согласия. Реплика считается согласием, только если **все** её слова
#: отсюда: «да» и «да давай» — согласие, «да, но сначала» — нет.
YES_WORDS = frozenset({
    "да", "ага", "угу", "давай", "давайте", "конечно", "подтверждаю",
    "валяй", "ок", "окей", "хорошо", "ладно", "разрешаю", "точно", "верно",
    "именно", "делай", "сделай", "отправляй", "продолжай", "ясно", "добро",
    "yes", "yeah", "yep", "yup", "sure", "ok", "okay", "go", "ahead",
    "confirm", "do", "it", "please", "affirmative", "right",
})

#: Что считать словом: всё, что не буква и не цифра, — разделитель.
_WORDS = re.compile(r"[^\W_]+", re.UNICODE)


def words(text: str) -> list[str]:
    """Слова реплики в нижнем регистре, без знаков препинания."""
    return _WORDS.findall(text.lower())


def answer(text: str) -> bool | None:
    """Разобрать реплику как ответ на вопрос «да или нет».

    :return: ``True`` — согласие, ``False`` — отказ, ``None`` — это не ответ.

    Порядок проверок не переставлять: отказ ищется первым, потому что слова
    согласия часто стоят перед ним («конечно нет», «да не надо»).
    """
    parts = words(text)
    if not parts or len(parts) > MAX_WORDS:
        return None
    if any(part in NO_MARKERS for part in parts):
        return False
    if all(part in YES_WORDS for part in parts):
        return True
    return None


@dataclass(frozen=True, slots=True, kw_only=True)
class Pending:
    """Заданный вопрос и то, что произойдёт при согласии."""

    #: Что выполнить, если ответят «да». Обычный `Intent`: подтверждённый шаг
    #: не получает никаких особых прав, он идёт тем же путём, что и голосовая
    #: команда.
    intent: Intent
    question: str = ""
    language: str = "ru"
    #: Момент, после которого вопрос считается протухшим.
    until: float = 0.0

    @classmethod
    def about(
        cls, intent: Intent, *, question: str = "", language: str = "ru", ttl: float = TTL
    ) -> "Pending":
        """Завести вопрос со сроком годности от текущего момента."""
        return cls(
            intent=intent,
            question=question,
            language=language,
            until=time.time() + ttl,
        )

    def alive(self, now: float | None = None) -> bool:
        """Не протух ли вопрос."""
        return (now if now is not None else time.time()) < self.until
